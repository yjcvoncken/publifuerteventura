class SiteTranslationMiddleware:
    def __init__(self, get_response): self.get_response = get_response

    def __call__(self, request):
        response = self.get_response(request)
        lang = getattr(request, "LANGUAGE_CODE", "en")[:2]
        if lang not in {"es", "it"} or not response.get("Content-Type", "").startswith("text/html"):
            return response
        index = 0 if lang == "es" else 1
        html = response.content.decode(response.charset)
        for source, translated in sorted(COPY.items(), key=lambda item: len(item[0]), reverse=True):
            html = html.replace(source, translated[index])
        html = html.replace('<html lang="en">', f'<html lang="{lang}">')
        response.content = html.encode(response.charset)
        response["Content-Length"] = len(response.content)
        return response
